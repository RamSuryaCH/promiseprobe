import path from 'node:path';
import type { ScenarioId, Verdict, Witness } from './types.js';

export interface WitnessCase {
  scenario: ScenarioId;
  delayMs?: number;
  verdict: Verdict;
}

function posixRelative(fromFile: string, toFile: string): string {
  return relativeFrom(path.dirname(fromFile), toFile);
}

function relativeFrom(fromDir: string, toFile: string): string {
  let rel = path.relative(fromDir, toFile).split(path.sep).join('/');
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

export function renderWitness(options: {
  witnessFile: string;
  probeFile: string;
  libraryEntry: string;
  promiseName: string;
  cases: WitnessCase[];
}): string {
  const probeImport = posixRelative(options.witnessFile, options.probeFile);
  const libImport = posixRelative(options.witnessFile, options.libraryEntry);
  const packageRoot = path.resolve(path.dirname(options.libraryEntry), '..');
  const rerunPath = relativeFrom(packageRoot, options.witnessFile).replace(/^\.\//, '');
  const cases = options.cases
    .map((item) => {
      const delay = item.delayMs == null ? '' : `, delayMs: ${item.delayMs}`;
      return `  { scenario: '${item.scenario}'${delay}, verdict: '${item.verdict}' },`;
    })
    .join('\n');

  return `/**
 * Generated by PromiseProbe.
 * Minimal failing witness for "${options.promiseName}".
 *
 * Re-run from the package root:
 *   npx tsx ${rerunPath}
 */
import assert from 'node:assert/strict';
import { reproduce, startApp } from '${libImport}';
import probe from '${probeImport}';

const cases = [
${cases}
];

const stop = await startApp(probe);
try {
  for (const item of cases) {
    const result = await reproduce(probe, {
      scenario: item.scenario,
      delayMs: item.delayMs,
    });
    console.log(\`\${item.scenario}: \${result.verdict ?? result.error}\`);
    assert.equal(result.verdict, item.verdict);
  }
} finally {
  await stop();
}
`;
}

export function witnessCases(witnesses: Witness[]): WitnessCase[] {
  return witnesses.map((witness) => ({
    scenario: witness.scenario,
    delayMs: witness.delayMs,
    verdict: witness.verdict,
  }));
}
